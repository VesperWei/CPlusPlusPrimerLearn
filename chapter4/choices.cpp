#include<iostream>
#include<vector>
#include<array>

int main()
{
    using namespace std;

    double a1[4] = {1.2, 2.4, 3.41 ,4.8};

/*
    栈（stack）                          堆（heap）
┌─────────────────┐                 ┌─────────────────┐
│  vector object  │                 │  double[4] array│
│  small，~24byte │                 │  1.01           │
│  - data pointer │   ─────→        │  1.11           │
│  - size         │                 │  1.21           │
│  - capacity     │                 │  1.31           │
└─────────────────┘                 └─────────────────┘
vector是堆管理器，在退出作用域时，自动调用它的析构函数，销毁分配在堆上的空间
*/
    //4是构造函数的参数，vector初始化时数组个数能使用变量
    vector<double> a2(4);
    a2[0] = 1.01;
    a2[1] = 1.11;
    a2[2] = 1.21;
    a2[3] = 1.31;

    //array不使用堆，只使用栈，理解为是C++11中对传统数组的升级
    //array<double, 4>是模板实例，4是模板参数，数组个数与传统数组一样，只能用常量
    array<double, 4> a3 = {1.41, 1.51, 1.61, 1.71};
    array<double, 4> a4;
    
    //赋值操作，传统数组不支持
    a4 = a3;

    cout << "a1[2]: " << a1[2] << " at " << &a1[2] << endl;
    cout << "a2[2]: " << a2[2] << " at " << &a2[2] << endl;
    cout << "a3[2]: " << a3[2] << " at " << &a3[2] << endl;
    cout << "a4[2]: " << a4[2] << " at " << &a4[2] << endl;

    // a1[6]等价*(a1 + 6)
    a1[6] = 20.1;
    cout << "a1[6]: " << a1[6] << " at " << &a1[6] << endl;
    cout << "a3[2]: " << a3[2] << " at " << &a3[2] << endl;
    cout << "a4[2]: " << a4[2] << " at " << &a4[2] << endl;

    a2[6] = 20.2;
    cout << "a2[6]: " << a2[6] << " at " << &a2[6] << endl;
    //会抛异常
    //a2.at(6) = 20.2;

    a3[6] = 20.3;
    cout << "a3[6]: " << a3[6] << " at " << &a3[6] << endl;
    //会抛异常
    //a3.at(6) = 20.2;

    //vector的实际数组在堆上，要用sizeof得到的是栈上变量的大小，不是数组大小
    //array和传统数组都放在栈上，且大小一致
    cout << "sizeof(a1) = " << sizeof(a1) << " bytes" << endl;
    cout << "a1 size is = " << sizeof(a1)/sizeof(a1[0])  << " nums"  << endl;
    cout << "sizeof(a2) = " << sizeof(a2) << " bytes" << endl;
    cout << "a2.size() = "  << a2.size()  << " nums"  << endl;
    cout << "sizeof(a3) = " << sizeof(a3) << " bytes" << endl;
    cout << "a3.size() = "  << a3.size()  << " nums"  << endl;


/*
 * ============================================================
 *  std::array vs 传统 C 数组 对比表
 * ============================================================
 *
 * 特性                  C 数组 double[4]        std::array<double,4>
 * ─────────────────────────────────────────────────────────────────
 * 内存开销              32 字节                 32 字节（完全相同）
 * 运行时开销            无                      无（零开销抽象）
 * 赋值操作              ❌ 不支持                ✅ 支持
 * 获取大小              ❌ 不方便                ✅ size()
 * 边界检查              ❌ 无                   ✅ at()
 * 传参保留类型          ❌ 退化为指针            ✅ 保留
 * 支持迭代器            ⚠️ C++11 后才可以       ✅ 原生支持
 * 兼容 C 库函数         ✅ 直接用                ✅ data() 取指针
 * ─────────────────────────────────────────────────────────────────
 */


    return 0;
}